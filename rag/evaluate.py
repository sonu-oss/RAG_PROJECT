"""Retrieval evaluation: compare bm25, vector and hybrid on a labeled question set.

Each question in eval/questions.jsonl lists the passages that answer it as
{"source": file name, "contains": a phrase from the passage}. A retrieved chunk
counts as relevant when it comes from that file and contains that phrase, so
the labels keep working if the chunk size changes. Every label is checked
against the index before scoring: a label that matches no chunk is an error,
not a silent miss.

Metrics, averaged over questions:
- recall@k: share of a question's relevant passages found in the top k
- MRR@10: 1 / rank of the first relevant chunk (0 if none in the top 10)
"""

import json
import tempfile
import time
from dataclasses import dataclass
from pathlib import Path

from .config import Settings
from .embeddings import Embedder
from .search import HybridSearcher

MODES = ("bm25", "vector", "hybrid")
KS = (1, 3, 5)
MRR_DEPTH = 10


def _norm(s: str) -> str:
    return " ".join(s.lower().split())


@dataclass
class Question:
    id: str
    type: str
    question: str
    relevant: list[dict]


def load_questions(path: str | Path) -> list[Question]:
    lines = Path(path).read_text().splitlines()
    return [Question(**json.loads(line)) for line in lines if line.strip()]


def _matches(chunk, label: dict) -> bool:
    return chunk.source == label["source"] and _norm(label["contains"]) in _norm(chunk.text)


def check_labels(hs: HybridSearcher, questions: list[Question]) -> None:
    bad = [
        f"{q.id}: {lab}"
        for q in questions
        for lab in q.relevant
        if not any(_matches(c, lab) for c in hs.chunks.values())
    ]
    if bad:
        raise ValueError("These labels match no chunk in the index:\n  " + "\n  ".join(bad))


def score_question(hs: HybridSearcher, q: Question, mode: str) -> dict:
    t0 = time.perf_counter()
    results = hs.search(q.question, k=MRR_DEPTH, mode=mode)
    ms = (time.perf_counter() - t0) * 1000
    # rank (1-based) at which each label is first found, None if not in the top 10
    found = []
    for lab in q.relevant:
        rank = next((i for i, r in enumerate(results, 1) if _matches(r.chunk, lab)), None)
        found.append(rank)
    hit_ranks = [r for r in found if r is not None]
    row = {f"recall@{k}": sum(1 for r in hit_ranks if r <= k) / len(q.relevant) for k in KS}
    row["mrr"] = 1 / min(hit_ranks) if hit_ranks else 0.0
    row["first_rank"] = min(hit_ranks) if hit_ranks else None
    row["ms"] = ms
    return row


def _mean(rows: list[dict], key: str) -> float:
    return sum(r[key] for r in rows) / len(rows) if rows else 0.0


def run(questions_path: str | Path, docs: str | Path, embedder: Embedder | None = None) -> dict:
    questions = load_questions(questions_path)
    with tempfile.TemporaryDirectory() as tmp:
        hs = HybridSearcher(Settings(index_dir=Path(tmp)), embedder=embedder)
        hs.ingest(docs, reset=True)
        check_labels(hs, questions)
        for q in questions[:2]:  # warm up so the first timed query isn't slow
            hs.search(q.question, k=MRR_DEPTH)
        per_q = {m: [score_question(hs, q, m) for q in questions] for m in MODES}
        stats = hs.stats()

    types = sorted({q.type for q in questions})
    keys = [f"recall@{k}" for k in KS] + ["mrr", "ms"]
    summary = {m: {key: _mean(per_q[m], key) for key in keys} for m in MODES}
    by_type = {
        t: {
            m: {
                key: _mean([row for q, row in zip(questions, per_q[m]) if q.type == t], key)
                for key in keys
            }
            for m in MODES
        }
        for t in types
    }
    details = [
        {"id": q.id, "type": q.type, "question": q.question,
         **{m: per_q[m][i]["first_rank"] for m in MODES}}
        for i, q in enumerate(questions)
    ]
    return {
        "embedder": stats["embedder"],
        "docs": str(docs),
        "files": stats["sources"],
        "chunks": stats["chunks"],
        "questions": len(questions),
        "count_by_type": {t: sum(q.type == t for q in questions) for t in types},
        "summary": summary,
        "by_type": by_type,
        "details": details,
    }


def to_markdown(res: dict) -> str:
    f = lambda x: f"{x:.3f}"  # noqa: E731
    out = [
        "# Retrieval evaluation",
        "",
        f"{res['questions']} labeled questions over `{res['docs']}` "
        f"({res['files']} files, {res['chunks']} chunks). "
        f"Embedder: `{res['embedder']}`. Generated by `python cli.py eval`.",
        "",
        "| Mode | Recall@1 | Recall@3 | Recall@5 | MRR@10 | ms / query |",
        "|---|---|---|---|---|---|",
    ]
    best = {k: max(res["summary"][m][k] for m in MODES) for k in ("recall@1", "recall@3", "recall@5", "mrr")}
    for m in MODES:
        s = res["summary"][m]
        cells = [f"**{f(s[k])}**" if s[k] == best[k] else f(s[k]) for k in ("recall@1", "recall@3", "recall@5", "mrr")]
        out.append(f"| {m} | " + " | ".join(cells) + f" | {s['ms']:.1f} |")

    out += [
        "",
        "## By question type",
        "",
        "| Type | Questions | BM25 R@5 / MRR | Vector R@5 / MRR | Hybrid R@5 / MRR |",
        "|---|---|---|---|---|",
    ]
    for t, modes in res["by_type"].items():
        cells = [f"{f(modes[m]['recall@5'])} / {f(modes[m]['mrr'])}" for m in MODES]
        out.append(f"| {t} | {res['count_by_type'][t]} | " + " | ".join(cells) + " |")

    out += [
        "",
        "Types: `keyword` questions name an exact identifier (error code, header, parameter); "
        "`paraphrase` questions use plain words that mostly differ from the docs; "
        "`factual` questions share some words with the answer.",
        "",
        "## Per question",
        "",
        "Rank of the first relevant chunk in each mode (`-` = not in the top 10).",
        "",
        "| Id | Type | Question | BM25 | Vector | Hybrid |",
        "|---|---|---|---|---|---|",
    ]
    for d in res["details"]:
        ranks = [str(d[m]) if d[m] else "-" for m in MODES]
        out.append(f"| {d['id']} | {d['type']} | {d['question']} | " + " | ".join(ranks) + " |")
    return "\n".join(out) + "\n"
